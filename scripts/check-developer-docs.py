"""Check developer links and the generated source inventory; no third-party packages.

Run with --write-inventory after reviewing source/header additions. The inventory
is a file/declaration index, not a substitute for curated subsystem explanations.
Only this explicitly requested mode writes files; the normal mode is read-only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import unicodedata
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = Path("docs/developers/source-inventory.md")
SOURCE_ROOTS = {
    "EVA", "EVACore", "EVAPreviewKit", "EVAQuickLook", "EVAThumbnail",
    "EVAResolve", "EVATests", "EVAUITests", "EVAResolveTests", "Tools", "scripts",
}
SOURCE_SUFFIXES = {".swift", ".metal", ".py", ".sh", ".c", ".h", ".cpp", ".m", ".mm", ".js", ".html"}
LINK = re.compile(r"!?\[[^\]\n]*\]\(([^)\n]+)\)")


def source_paths(root: Path) -> list[Path]:
    """Include tracked and new unignored source files in declared product/tool roots."""
    output = subprocess.check_output(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=root
    ).decode()
    return sorted({Path(name) for name in output.split("\0") if name
                   and Path(name).suffix in SOURCE_SUFFIXES
                   and (Path(name).parts[0] in SOURCE_ROOTS
                        or len(Path(name).parts) == 1
                        or name.startswith("docs/figures/"))
                   and (root / name).is_file()})


def leading_comment(text: str) -> str:
    """Retain a header fingerprint so changed contracts prompt inventory review."""
    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith(("//", "#", "/*", "*")):
            lines.append(line)
        else:
            break
    return "\n".join(lines)


def declarations(text: str, suffix: str) -> str:
    """Show a few literal source declarations, without inventing a semantic synopsis."""
    pattern = r"^\s*(?:(?:nonisolated|public|private|final|internal|open)\s+)*(?:struct|class|enum|protocol|extension)\s+(\w+)"
    names = re.findall(pattern, text, re.M) if suffix == ".swift" else []
    if suffix == ".py":
        names = re.findall(r"^(?:def|class)\s+(\w+)", text, re.M)
    if suffix == ".sh":
        names = re.findall(r"^([\w-]+)\s*\(\)\s*\{", text, re.M)
    if suffix == ".metal":
        names = re.findall(r"\bkernel\s+void\s+(\w+)", text)
    names = list(dict.fromkeys(names))
    return ", ".join(f"`{n}`" for n in names[:4]) + ("; …" if len(names) > 4 else "") if names else "File-level code / supporting declarations"


def inventory_text(root: Path) -> str:
    paths = source_paths(root)
    text = """# Complete source-file inventory

Generated by `python3 scripts/check-developer-docs.py --write-inventory`.
Do not hand-edit this file. Use the [feature map](features.md) and
[subsystem explanations](subsystems/README.md) to understand responsibilities.
This index provides a link and literal entry declarations for every in-scope
source file, including tests, CLI tools, and scripts. Hidden header fingerprints
make header changes require regeneration/review; they do not prove prose correct.

Scope: tracked and new unignored source files in EVA/product/test roots, Tools,
scripts, repository-root source scripts, and docs/figures source. Extensions are
Swift, Metal, Python, shell, C/C++/Objective-C, JavaScript, and HTML. Excluded:
generated build products, vendored/local resources, binary fixtures and assets,
project/configuration files, prose, and tutorial patches (checked separately).
The historical readability scorecard has its own frozen assessment population;
this current inventory can have a different count without changing those scores.

"""
    text += f"**{len(paths)} source files.**\n"
    fingerprints = []
    group = None
    for path in paths:
        current = "/".join(path.parts[:2]) if len(path.parts) > 2 else path.parts[0]
        if current != group:
            text += f"\n## {current}\n\n| File | Entry declarations |\n| --- | --- |\n"
            group = current
        source = (root / path).read_text(errors="replace")
        digest = hashlib.sha256(leading_comment(source).encode()).hexdigest()[:16]
        text += f"| [{path.as_posix()}](../../{path.as_posix()}) | {declarations(source, path.suffix)} |\n"
        fingerprints.append(f"header {path.as_posix()} {digest}")
    return text + "\n<!--\n" + "\n".join(fingerprints) + "\n-->\n"


def prose_only(text: str) -> str:
    """Remove fenced examples before inspecting Markdown links and headings."""
    output = []
    fence = None
    for line in text.splitlines(keepends=True):
        marker = re.match(r"^\s*(`{3,}|~{3,})", line)
        if marker:
            token = marker.group(1)
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
        elif fence is None:
            output.append(line)
    return "".join(output)


def heading_ids(text: str) -> set[str]:
    """GitHub-style heading identifiers, including duplicated heading suffixes."""
    ids: set[str] = set()
    counts: dict[str, int] = {}
    for heading in re.findall(r"^#{1,6}\s+(.+?)\s*#*\s*$", prose_only(text), re.M):
        heading = re.sub(r"\[([^]]+)\]\([^)]+\)", r"\1", heading)
        slug = "".join(c for c in heading.lower() if c in "-_ " or unicodedata.category(c)[0] in "LN").replace(" ", "-")
        number = counts.get(slug, 0)
        counts[slug] = number + 1
        ids.add(slug if number == 0 else f"{slug}-{number}")
    ids.update(re.findall(r'<a\s+(?:id|name)=["\']([^"\']+)', text))
    return ids


def check_links(root: Path, pages: list[Path]) -> list[str]:
    errors: list[str] = []
    for page in pages:
        text = page.read_text()
        for raw in LINK.findall(prose_only(text)):
            target = raw.strip().strip("<>")
            if target.startswith(("/Users/", "file://")):
                errors.append(f"{page.relative_to(root)}: machine-specific link {target}")
                continue
            url = urlsplit(target)
            if url.scheme or url.netloc:
                continue
            destination = (page.parent / unquote(url.path)).resolve() if url.path else page
            if not destination.is_relative_to(root.resolve()) or not destination.exists():
                errors.append(f"{page.relative_to(root)}: missing/outside repository: {target}")
            elif destination.suffix == ".md" and url.fragment and unquote(url.fragment) not in heading_ids(destination.read_text()):
                errors.append(f"{page.relative_to(root)}: missing heading: {target}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-inventory", action="store_true")
    args = parser.parse_args()
    expected = inventory_text(ROOT)
    destination = ROOT / INVENTORY
    if args.write_inventory:
        destination.write_text(expected)
        print(f"Wrote {INVENTORY}; review the inventory and affected subsystem prose.")
        return 0
    errors = []
    if not destination.exists() or destination.read_text() != expected:
        errors.append("Source inventory is stale: review changes, then run with --write-inventory.")
    pages = sorted((ROOT / "docs/developers").rglob("*.md"))
    errors.extend(check_links(ROOT, pages))
    contracts = ROOT / "docs/developers/source-contracts.json"
    for contract in json.loads(contracts.read_text()):
        source = ROOT / contract["file"]
        if not source.exists() or contract["symbol"] not in source.read_text():
            errors.append(f"Documented source entry point missing: {contract}")
    patches = sorted((ROOT / "docs/developers/examples").glob("*.patch"))
    for patch in patches:
        result = subprocess.run(["git", "apply", "--check", str(patch)],
                                cwd=ROOT, text=True, capture_output=True)
        if result.returncode:
            errors.append(f"Tutorial patch drift: {patch.name}\n{result.stderr.strip()}")
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    print(f"Developer docs: {len(pages)} pages, links/anchors, source inventory, "
          f"{len(patches)} patches and {len(json.loads(contracts.read_text()))} source contracts passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
